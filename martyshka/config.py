# ======================================================================
#  То, что поменяли в ОКНЕ НАСТРОЕК, хранится в data/settings.json и
#  перекрывает значения выше. (Здесь ничего менять не нужно.)
# ======================================================================
SETTINGS_FILE = DATA_DIR / "settings.json"


def _apply_settings_file() -> None:
    import json
    try:
        saved = json.loads(SETTINGS_FILE.read_text(encoding="utf-8"))
    except Exception:
        return
    g = globals()
    for key, value in saved.items():
        if key.isupper() and key in g:
            g[key] = Path(value) if isinstance(g[key], Path) and isinstance(value, str) else value


_apply_settings_file()
