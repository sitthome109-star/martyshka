def time_in_words(now: datetime) -> str:
    """16:07 → «шестнадцать ноль семь», 9:00 → «девять ровно»."""
    from num2words import num2words
    hours = num2words(now.hour, lang="ru") if now.hour else "ноль"
    if now.minute == 0:
        return f"{hours} ровно"
    minutes = num2words(now.minute, lang="ru")
    return f"{hours} {'ноль ' if now.minute < 10 else ''}{minutes}"


def build_system_prompt(facts: list[str], anger: int | None = None, source: str = "голос",
                        present: list[str] | None = None) -> str:
    """Собирает полную инструкцию: характер + дела (не меняются) → память, время, настроение (меняются)."""
    now = datetime.now()
    from num2words import num2words
    try:
        day = num2words(now.day, lang="ru", to="ordinal", gender="n")  # «шестнадцатое»
    except TypeError:
        day = str(now.day)
    when = (
        f"Сейчас {WEEKDAYS[now.weekday()]}, {now.day} {MONTHS[now.month - 1]} {now.year} года, время {now:%H:%M}. "
        f"Время называй словами так: «{time_in_words(now)}», дату — «{day} {MONTHS[now.month - 1]}». "
        f"Не верь времени из старых реплик."
    )
    memory = ("Что ты помнишь о брате:\n" + "\n".join(f"- {f}" for f in facts)) if facts else \
        "Пока ты ничего особенного о брате не запомнил."

    from . import longmem, style
    from .hands import actions_help
    common = COMMON.replace("{ACTIONS}", actions_help())
    if style.is_jarvis():
        sir = style.sir()
        for old, new in _JARVIS_SWAPS.items():
            common = common.replace(old, new.replace("{sir}", sir))
        character = (JARVIS_STYLE.format(name=config.NAME, sir=sir) + SOUL + style.adapt(common)
                     + JARVIS_TONE.format(name=config.NAME, sir=sir))
    else:
        character = BRO_STYLE + SOUL + common + BRO_TONE
    if config.PERSONALITY_EXTRA.strip():   # то, что брат дописал к характеру в окне настроек
        character += f"\nДополнительно от брата (важно, учитывай):\n{config.PERSONALITY_EXTRA.strip()}\n"
    lvl = longmem.anger(longmem.OWNER) if anger is None else anger
    mood = f"Твоя злость на брата сейчас: {lvl}/5 — {longmem.ANGER_WORDS[lvl]}."
    try:
        longterm = longmem.context(present=present, source=source)
    except Exception:
        longterm = ""
    tail = "\n\n".join(x for x in (memory, longterm, when, mood) if x)
    return style.adapt(f"{character}\n\n=== Сейчас ===\n{tail}")
